function RMPG.LangCode()
	if SERVER then return "en" end
	local v = RMPG.CL and RMPG.CL.lang:GetString() or "auto"
	if RMPG.Lang[v] then return v end
	local gl = GetConVar("gmod_language")
	local s = gl and gl:GetString() or "en"
	if s == "ru" or s == "uk" or s == "be" then return "ru" end
	return "en"
end

function RMPG.T(key, ...)
	local t = RMPG.Lang[RMPG.LangCode()] or RMPG.Lang.en
	local s = t[key] or RMPG.Lang.en[key] or key
	if select("#", ...) > 0 then
		local ok, res = pcall(string.format, s, ...)
		if ok then return res end
	end
	return s
end

